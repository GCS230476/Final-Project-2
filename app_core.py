@st.cache_data
def _load_results(stamp):
    data = {}
    p = MODELS_DIR / "all_10_models_comparison.csv"
    if p.exists():
        d = pd.read_csv(p, index_col=0)
        d.columns = [c.strip().lower() for c in d.columns]
        data["direction"] = d
    p = MODELS_DIR / "volatility_regression_results.csv"
