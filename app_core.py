@st.cache_data
def _load_price(stamp):
    """Accuracy-by-tolerance table + champion name, from notebook 09."""
    p = MODELS_DIR / "price_forecast_accuracy.csv"
    if not p.exists():
        return None
    acc = pd.read_csv(p)
    meta_p = MODELS_DIR / "price_meta.json"
    best = None
    if meta_p.exists():
        best = json.load(open(meta_p)).get("best_model")
    if best is None:                       # derive it the way the notebook does
        best = (acc[acc["tol_pip"].isin([50, 55, 60])]
                .groupby("model")["val"].mean().idxmax())
    return {"acc": acc, "best": best}


def load_price():
    return _load_price(_stamp(MODELS_DIR / "price_forecast_accuracy.csv",
                              MODELS_DIR / "price_meta.json"))


